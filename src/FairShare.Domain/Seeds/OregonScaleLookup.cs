    /// <summary>
    /// Oregon's Obligation Scale (the OAR 137-050-0725 appendix, form CSF 02 0809F Rev. 02/09/07),
    /// read from the "scale table" sheet of the official DOJ Guidelines Calculator workbook
    /// (justice.oregon.gov, saved 6/30/2026): key = (combined adjusted income row, number of
    /// children 1-10) -&gt; monthly basic support obligation in whole dollars.
    /// <list type="bullet">
    /// <item>Rows are "combined adjusted income equal to or greater than" thresholds: $0 (a flat $50
    /// row covering every income below $1,001), then $1,001 through $29,951 in $50 steps.</item>
    /// <item><see cref="Get"/> selects the highest threshold at or below the income — the lower
    /// bracket, never interpolating or rounding up (unlike Alabama's nearest-$50 lookup).</item>
    /// <item>Income at or above the top threshold uses the top row: Oregon caps at the $30,000 row,
    /// rebuttably, instead of erroring the calculation (unlike Alabama — ADR 0005).</item>
    /// </list>
    /// </summary>
    public static class OregonScaleLookup
    {
        /// <summary>Fewest children the scale has a column for.</summary>
        public const int MinChildren = 1;

        /// <summary>Most children the scale has a column for (more than 10 use the 10-child column, per OAR 137-050-0725).</summary>
        public const int MaxChildren = 10;

        /// <summary>Threshold of the top row; every income at or above it uses this row (the scale's cap).</summary>
        public const int TopThreshold = 29951;

        /// <summary>The row thresholds in ascending order, for lower-bracket selection.</summary>
        private static readonly int[] Thresholds;

        public static readonly Dictionary<(int Threshold, int Children), int> Table;

        static OregonScaleLookup()
        {
            Table = Seed();
            Thresholds = [.. Table.Keys.Select(k => k.Threshold).Distinct().OrderBy(t => t)];
        }

        /// <summary>
        /// Looks up the basic support obligation the way the official workbook does: the highest
        /// "equal to or greater than" threshold at or below the income. Incomes below the first
        /// threshold (including negative) use the $0 row; incomes above the top use the top row.
        /// </summary>
        /// <param name="combinedAdjustedIncome">Combined adjusted income in whole dollars. May be negative.</param>
        /// <param name="children">Number of children (1 to 10 inclusive).</param>
        /// <exception cref="ArgumentOutOfRangeException"><paramref name="children"/> is outside 1-10.</exception>
        public static int Get(int combinedAdjustedIncome, int children)
        {
            if (children < MinChildren || children > MaxChildren)
            {
                throw new ArgumentOutOfRangeException(nameof(children), $"Number of children must be between {MinChildren} and {MaxChildren}.");
            }

            return Table[(ThresholdFor(combinedAdjustedIncome), children)];
        }

        /// <summary>
        /// The scale row an income falls on: the highest threshold at or below it, clamped to the
        /// first and top rows at the extremes.
        /// </summary>
        public static int ThresholdFor(int combinedAdjustedIncome)
        {
            int index = Array.BinarySearch(Thresholds, combinedAdjustedIncome);

            if (index < 0)
            {
                // BinarySearch returns the complement of the next-larger element; the row below it
                // is the lower bracket. Clamp to the first row for incomes below every threshold.
                index = Math.Max(0, ~index - 1);
            }

            return Thresholds[index];
        }

        private static Dictionary<(int Threshold, int Children), int> Seed()
        {
            Dictionary<(int, int), int> dict = new(capacity: 5810);

            foreach (string line in Data.Split(['\n'], StringSplitOptions.RemoveEmptyEntries))
            {
                string[] parts = line.Split('|');

                if (parts.Length != 11)
                {
                    continue;
                }

                int threshold = int.Parse(parts[0], CultureInfo.InvariantCulture);

                for (int child = 1; child <= 10; child++)
                {
                    int val = int.Parse(parts[child], CultureInfo.InvariantCulture);
                    dict[(threshold, child)] = val;
                }
            }

            return dict;
        }

